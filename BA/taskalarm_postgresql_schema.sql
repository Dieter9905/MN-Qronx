-- TaskAlarm - Database schema for PostgreSQL 15+
-- Based on TaskAlarm_ERD.md. Run this script on a new/empty database.

BEGIN;

CREATE TABLE roles (
    role_id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_name VARCHAR(20) NOT NULL UNIQUE,
    description VARCHAR(255),
    CONSTRAINT ck_roles_role_name CHECK (role_name IN ('USER', 'ADMIN'))
);

CREATE TABLE app_users (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_id SMALLINT NOT NULL REFERENCES roles(role_id),
    full_name VARCHAR(150) NOT NULL,
    email VARCHAR(254) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    phone_number VARCHAR(20),
    avatar_url VARCHAR(500),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_app_users_full_name CHECK (length(trim(full_name)) > 0),
    CONSTRAINT ck_app_users_email_not_blank CHECK (length(trim(email)) > 0)
);

CREATE UNIQUE INDEX ux_app_users_email_lower ON app_users (lower(email));

CREATE TABLE password_reset_requests (
    reset_request_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_users(user_id),
    reset_token VARCHAR(255) NOT NULL UNIQUE,
    expires_at TIMESTAMPTZ NOT NULL,
    used_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_password_reset_requests_token CHECK (length(trim(reset_token)) > 0),
    CONSTRAINT ck_password_reset_requests_expiry CHECK (expires_at > created_at)
);

CREATE INDEX ix_password_reset_requests_user_id ON password_reset_requests (user_id);

CREATE TABLE categories (
    category_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_users(user_id),
    category_name VARCHAR(100) NOT NULL,
    color_code VARCHAR(20),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_categories_user_name UNIQUE (user_id, category_name),
    CONSTRAINT ck_categories_name CHECK (length(trim(category_name)) > 0)
);

CREATE INDEX ix_categories_user_id ON categories (user_id, is_active);

CREATE TABLE tasks (
    task_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_users(user_id),
    category_id BIGINT REFERENCES categories(category_id),
    parent_task_id BIGINT REFERENCES tasks(task_id),
    title VARCHAR(255) NOT NULL,
    description TEXT,
    priority VARCHAR(10) NOT NULL DEFAULT 'MEDIUM',
    status VARCHAR(20) NOT NULL DEFAULT 'TODO',
    due_at TIMESTAMPTZ NOT NULL,
    repeat_type VARCHAR(10) NOT NULL DEFAULT 'NONE',
    completed_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_tasks_title CHECK (length(trim(title)) > 0),
    CONSTRAINT ck_tasks_priority CHECK (priority IN ('LOW', 'MEDIUM', 'HIGH', 'URGENT')),
    CONSTRAINT ck_tasks_status CHECK (status IN ('TODO', 'IN_PROGRESS', 'COMPLETED', 'CANCELLED')),
    CONSTRAINT ck_tasks_repeat_type CHECK (repeat_type IN ('NONE', 'DAILY', 'WEEKLY', 'MONTHLY')),
    CONSTRAINT ck_tasks_not_self_parent CHECK (parent_task_id IS DISTINCT FROM task_id),
    CONSTRAINT ck_tasks_completed_data CHECK (
        (status = 'COMPLETED' AND completed_at IS NOT NULL)
        OR (status <> 'COMPLETED' AND completed_at IS NULL)
    )
);

CREATE INDEX ix_tasks_user_due ON tasks (user_id, due_at);
CREATE INDEX ix_tasks_user_status ON tasks (user_id, status);
CREATE INDEX ix_tasks_category_id ON tasks (category_id);
CREATE INDEX ix_tasks_parent_task_id ON tasks (parent_task_id);

CREATE TABLE subtasks (
    subtask_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id BIGINT NOT NULL REFERENCES tasks(task_id),
    content VARCHAR(255) NOT NULL,
    is_completed BOOLEAN NOT NULL DEFAULT FALSE,
    display_order INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_subtasks_content CHECK (length(trim(content)) > 0),
    CONSTRAINT ck_subtasks_display_order CHECK (display_order >= 0)
);

CREATE INDEX ix_subtasks_task_order ON subtasks (task_id, display_order);

CREATE TABLE reminders (
    reminder_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id BIGINT NOT NULL REFERENCES tasks(task_id),
    remind_at TIMESTAMPTZ NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'SCHEDULED',
    snooze_count SMALLINT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_reminders_status CHECK (status IN ('SCHEDULED', 'TRIGGERED', 'SNOOZED', 'DISMISSED', 'CANCELLED')),
    CONSTRAINT ck_reminders_snooze_count CHECK (snooze_count BETWEEN 0 AND 3)
);

-- Index chính phục vụ scheduler quét các reminder đến hạn kích hoạt.
CREATE INDEX ix_reminders_status_remind_at ON reminders (status, remind_at);
CREATE INDEX ix_reminders_task_id ON reminders (task_id);

CREATE TABLE devices (
    device_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_users(user_id),
    device_token VARCHAR(500) NOT NULL UNIQUE,
    platform VARCHAR(10) NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_devices_platform CHECK (platform IN ('WEB', 'ANDROID', 'IOS')),
    CONSTRAINT ck_devices_token CHECK (length(trim(device_token)) > 0)
);

CREATE INDEX ix_devices_user_id ON devices (user_id, is_active);

CREATE TABLE notification_logs (
    notification_log_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reminder_id BIGINT NOT NULL REFERENCES reminders(reminder_id),
    device_id BIGINT REFERENCES devices(device_id),
    action VARCHAR(10) NOT NULL,
    sent_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_notification_logs_action CHECK (action IN ('SENT', 'SNOOZED', 'DISMISSED'))
);

CREATE INDEX ix_notification_logs_reminder_id ON notification_logs (reminder_id, sent_at DESC);
CREATE INDEX ix_notification_logs_device_id ON notification_logs (device_id);

CREATE TABLE notification_settings (
    notification_setting_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL UNIQUE REFERENCES app_users(user_id),
    alarm_sound VARCHAR(50) NOT NULL DEFAULT 'DEFAULT',
    default_snooze_minutes SMALLINT NOT NULL DEFAULT 5,
    vibration_enabled BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_notification_settings_snooze_minutes CHECK (default_snooze_minutes > 0)
);

-- A reminder's remind_at must not be later than its task's due_at,
-- and a task may not have more than 5 non-cancelled reminders.
CREATE OR REPLACE FUNCTION validate_reminder()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    v_due_at TIMESTAMPTZ;
    v_active_count INTEGER;
BEGIN
    SELECT due_at INTO v_due_at FROM tasks WHERE task_id = NEW.task_id;

    IF v_due_at IS NULL THEN
        RAISE EXCEPTION 'Task % không tồn tại', NEW.task_id;
    END IF;

    IF NEW.remind_at > v_due_at THEN
        RAISE EXCEPTION 'Thời điểm nhắc nhở phải nhỏ hơn hoặc bằng thời hạn công việc';
    END IF;

    SELECT COUNT(*) INTO v_active_count
    FROM reminders
    WHERE task_id = NEW.task_id
      AND status <> 'CANCELLED'
      AND reminder_id <> COALESCE(NEW.reminder_id, -1);

    IF v_active_count >= 5 THEN
        RAISE EXCEPTION 'Mỗi công việc chỉ được có tối đa 5 nhắc nhở đang hoạt động';
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_reminders_validate
BEFORE INSERT OR UPDATE OF task_id, remind_at, status ON reminders
FOR EACH ROW
EXECUTE FUNCTION validate_reminder();

-- A task's parent_task_id, if set, must reference another task owned by the same user.
CREATE OR REPLACE FUNCTION validate_task_parent()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    v_parent_user_id BIGINT;
BEGIN
    IF NEW.parent_task_id IS NOT NULL THEN
        SELECT user_id INTO v_parent_user_id FROM tasks WHERE task_id = NEW.parent_task_id;

        IF v_parent_user_id IS NULL THEN
            RAISE EXCEPTION 'Task cha % không tồn tại', NEW.parent_task_id;
        END IF;

        IF v_parent_user_id <> NEW.user_id THEN
            RAISE EXCEPTION 'Task cha phải thuộc cùng User với Task hiện tại';
        END IF;
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_tasks_validate_parent
BEFORE INSERT OR UPDATE OF parent_task_id, user_id ON tasks
FOR EACH ROW
EXECUTE FUNCTION validate_task_parent();

CREATE TABLE refresh_tokens (
    token_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_users(user_id),
    token VARCHAR(500) NOT NULL UNIQUE,
    expires_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_refresh_tokens_token CHECK (length(trim(token)) > 0),
    CONSTRAINT ck_refresh_tokens_expiry CHECK (expires_at > created_at)
);

CREATE INDEX ix_refresh_tokens_user_id ON refresh_tokens (user_id);
CREATE INDEX ix_refresh_tokens_token ON refresh_tokens (token);

INSERT INTO roles (role_name, description)
VALUES
    ('USER', 'Người dùng quản lý công việc cá nhân'),
    ('ADMIN', 'Quản trị viên hệ thống')
ON CONFLICT (role_name) DO NOTHING;

COMMIT;
